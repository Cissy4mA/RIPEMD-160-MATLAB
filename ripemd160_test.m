% ripemd160_test.m
% Verify this MATLAB RIPEMD-160 implementation against the standard
% RIPEMD-160 test vectors published by the RIPEMD developers.
% Run:  ripemd160_test
%
% Each test message is written to a temporary file (no trailing newline),
% then hashed with ripemd160(). The result is compared case-insensitively
% against the known digest.

tests = { ...
    ''; ...
    'a'; ...
    'abc'; ...
    'message digest'; ...
    'abcdefghijklmnopqrstuvwxyz'; ...
    'abcdbcdecdefdefgefghfghighijhijkijkljklmklmnlmnomnopnopq'; ...
    'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789' };

expected = { ...
    '9c1185a5c5e9fc54612808977ee8f548b2258d31'; ...
    '0bdc9d2d256b3ee9daae347be6f4dc835a467ffe'; ...
    '8eb208f7e05d987a9b044a8e98c6b087f15a0bfc'; ...
    '5d0689ef49d2fae572b881b123a85ffa21595f36'; ...
    'f71c27109c692c1b56bbdceb5b9d2865b3708dbc'; ...
    '12a053384a9c0c88e405a06c27dcf49ada62eb2b'; ...
    'b0e20b6e3116640286ed3a87a5713079b21f5189' };

allpass = true;
for i = 1:numel(tests)
    fname = sprintf('ripemd160_test_tmp_%d.txt', i);
    fid = fopen(fname, 'w');
    fwrite(fid, tests{i}, 'char');
    fclose(fid);
    got = lower(ripemd160(fname));
    delete(fname);
    pass = strcmp(got, expected{i});
    allpass = allpass && pass;
    fprintf('%-2d  %-5s  %s\n', i, string(pass), got);
end

fprintf('\nAll test vectors passed: %s\n', string(allpass));
